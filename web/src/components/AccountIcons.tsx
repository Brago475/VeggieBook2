// Icons for the account screen. Inline so the app takes no icon
// dependency. All are decorative: each sits next to text that already says
// what it means, or inside a button that has its own label.

type IconProps = { className?: string }

function Svg({ className, children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  )
}

// Filled rather than outlined: it is the avatar, the largest icon on the
// screen, and a solid shape reads better at that size.

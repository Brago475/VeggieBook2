-- Playlists: admin-made lists of tips and recipes sent through notifications,
-- and lists people make from recipes in their saved books. Book tables are
-- not changed. Item ids are checked by the API against the content tables.

BEGIN;

CREATE TABLE IF NOT EXISTS playlist (
    id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_en     text        NOT NULL,
    name_es     text,
    archived_at timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now(),
    created_by  uuid,
    updated_at  timestamptz,
    updated_by  uuid,
    CONSTRAINT playlist_name_en_length CHECK (char_length(btrim(name_en)) BETWEEN 1 AND 80),
    CONSTRAINT playlist_name_es_length CHECK (name_es IS NULL OR char_length(name_es) <= 80)
);

-- item_id is tip.id or recipe.id, depending on kind.
CREATE TABLE IF NOT EXISTS playlist_item (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id int        NOT NULL REFERENCES playlist(id) ON DELETE CASCADE,
    position    int        NOT NULL,
    kind        varchar(8) NOT NULL CHECK (kind IN ('tip', 'recipe')),
    item_id     int        NOT NULL
);

CREATE INDEX IF NOT EXISTS playlist_item_order ON playlist_item (playlist_id, position);

-- Keep or Skip, one row per account and playlist. Removing a kept playlist
-- sets kept to false.
CREATE TABLE IF NOT EXISTS playlist_choice (
    playlist_id     int         NOT NULL REFERENCES playlist(id),
    user_id         uuid        NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    kept            boolean     NOT NULL,
    notification_id int         REFERENCES notification(id),
    decided_at      timestamptz NOT NULL,
    PRIMARY KEY (playlist_id, user_id)
);

CREATE TABLE IF NOT EXISTS user_playlist (
    id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    uuid        NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    name       text        NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz,
    CONSTRAINT user_playlist_name_length CHECK (char_length(btrim(name)) BETWEEN 1 AND 60)
);

CREATE INDEX IF NOT EXISTS user_playlist_owner ON user_playlist (user_id);

-- recipe_id must be a kept recipe in one of the owner's books when added.
CREATE TABLE IF NOT EXISTS user_playlist_item (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_playlist_id int NOT NULL REFERENCES user_playlist(id) ON DELETE CASCADE,
    position         int NOT NULL,
    recipe_id        int NOT NULL
);

CREATE INDEX IF NOT EXISTS user_playlist_item_order ON user_playlist_item (user_playlist_id, position);

-- A notification can open one playlist.
ALTER TABLE notification ADD COLUMN IF NOT EXISTS playlist_id int REFERENCES playlist(id);

ALTER TABLE activity_log DROP CONSTRAINT activity_log_kind_check;

ALTER TABLE activity_log ADD CONSTRAINT activity_log_kind_check CHECK (kind IN (
    'book_saved',
    'book_deleted',
    'account_deleted',
    'study_renamed',
    'study_deleted',
    'item_removed',
    'book_printed',
    'book_downloaded',
    'research_erased',
    'notification_shown',
    'notification_opened',
    'notification_link',
    'notification_dismissed',
    'notification_created',
    'notification_edited',
    'notification_stopped',
    'playlist_created',
    'playlist_edited',
    'playlist_archived',
    'playlist_opened',
    'playlist_kept',
    'playlist_skipped',
    'playlist_removed',
    'playlist_item_opened',
    'user_playlist_created',
    'user_playlist_edited',
    'user_playlist_deleted'
));

COMMIT;